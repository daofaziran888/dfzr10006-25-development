    """给 MOCK-0002 预置两个批次：B001 已转入历史，B002 是当前唯一有效批次。

    批次边界：一次生成动作产生一个批次，归属（配置编号 + 数据模板）；
    同一配置同一模板只保留一个有效批次，旧批次保留为历史但不进入当前模拟响应。
    """
    config = next(row for row in SEED_ROWS["mock"] if row["配置编号"] == "MOCK-0002")
    count = int(config["生成条数"])
    batches: list[dict[str, Any]] = []
    for seq, status, created_at in ((1, "历史", "2026-11-10 09:30:00"), (2, "有效", "2026-11-12 14:00:00")):
        batch_no = f"MOCK-0002-B{seq:03d}"
        records = generate_records(config["字段规则"], count, batch_no)
        batches.append({
            "id": seq,
            "批次编号": batch_no,
            "配置编号": config["配置编号"],
            "模拟对象": config["模拟对象"],
            "数据模板": config["数据模板"],
            "模板格式": config["模板格式"],
            "生成条数": count,
            "实际条数": len(records),
            "字段规则": config["字段规则"],
            "批次状态": status,
            "生成时间": created_at,
            "records": records,
        })
    return batches


